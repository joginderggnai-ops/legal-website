'use strict';
// Database: Postgres when DATABASE_URL is set (Vercel + Neon), otherwise a SQLite file (local, VPS).
// Queries are written once with "?" placeholders. Timestamps are UTC text "YYYY-MM-DD HH:MM:SS"
// passed in from JavaScript (see nowSql), so no database-specific date functions are needed.
const fs = require('node:fs');
const config = require('./config');

const isPg = Boolean(config.databaseUrl);

// UTC "YYYY-MM-DD HH:MM:SS", optionally offset (e.g. -30 days) — the format every *_at column uses.
function nowSql(offsetMs = 0) {
  return new Date(Date.now() + offsetMs).toISOString().slice(0, 19).replace('T', ' ');
}

function schema() {
  const id = isPg ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY';
  const now = isPg ? "to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')" : "(strftime('%Y-%m-%d %H:%M:%S', 'now'))";
  return [
    `CREATE TABLE IF NOT EXISTS users (
      id            ${id},
      email         TEXT NOT NULL UNIQUE,
      name          TEXT NOT NULL,
      role          TEXT NOT NULL DEFAULT 'editor' CHECK (role IN ('admin', 'editor')),
      password_hash TEXT NOT NULL,
      active        INTEGER NOT NULL DEFAULT 1,
      created_at    TEXT NOT NULL DEFAULT ${now},
      last_login_at TEXT
    )`,
    `CREATE TABLE IF NOT EXISTS sessions (
      token_hash TEXT PRIMARY KEY,
      user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      csrf       TEXT NOT NULL,
      expires_at BIGINT NOT NULL,
      created_at TEXT NOT NULL DEFAULT ${now}
    )`,
    `CREATE TABLE IF NOT EXISTS leads (
      id            ${id},
      name          TEXT NOT NULL,
      email         TEXT NOT NULL,
      phone         TEXT NOT NULL DEFAULT '',
      company       TEXT NOT NULL DEFAULT '',
      practice_area TEXT NOT NULL DEFAULT '',
      message       TEXT NOT NULL DEFAULT '',
      page          TEXT NOT NULL DEFAULT '',
      ip            TEXT NOT NULL DEFAULT '',
      user_agent    TEXT NOT NULL DEFAULT '',
      status        TEXT NOT NULL DEFAULT 'new',
      assigned_to   INTEGER REFERENCES users(id) ON DELETE SET NULL,
      created_at    TEXT NOT NULL DEFAULT ${now},
      updated_at    TEXT NOT NULL DEFAULT ${now}
    )`,
    'CREATE INDEX IF NOT EXISTS leads_created ON leads (created_at DESC)',
    'CREATE INDEX IF NOT EXISTS leads_status ON leads (status)',
    // Notes and status changes on a lead, newest first in the UI.
    `CREATE TABLE IF NOT EXISTS lead_activity (
      id         ${id},
      lead_id    INTEGER NOT NULL REFERENCES leads(id) ON DELETE CASCADE,
      user_id    INTEGER REFERENCES users(id) ON DELETE SET NULL,
      body       TEXT NOT NULL,
      created_at TEXT NOT NULL DEFAULT ${now}
    )`,
    'CREATE INDEX IF NOT EXISTS lead_activity_lead ON lead_activity (lead_id, created_at DESC)',
    `CREATE TABLE IF NOT EXISTS posts (
      id               ${id},
      title            TEXT NOT NULL,
      slug             TEXT NOT NULL UNIQUE,
      excerpt          TEXT NOT NULL DEFAULT '',
      body             TEXT NOT NULL DEFAULT '',
      category         TEXT NOT NULL DEFAULT '',
      author_name      TEXT NOT NULL DEFAULT '',
      cover_image      TEXT NOT NULL DEFAULT '',
      cover_alt        TEXT NOT NULL DEFAULT '',
      meta_title       TEXT NOT NULL DEFAULT '',
      meta_description TEXT NOT NULL DEFAULT '',
      status           TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'published')),
      published_at     TEXT,
      created_by       INTEGER REFERENCES users(id) ON DELETE SET NULL,
      created_at       TEXT NOT NULL DEFAULT ${now},
      updated_at       TEXT NOT NULL DEFAULT ${now}
    )`,
    'CREATE INDEX IF NOT EXISTS posts_published ON posts (status, published_at DESC)'
  ];
}

/* ---------------------------------------------------------------- Drivers */

let driver;

if (isPg) {
  const { Pool, types } = require('pg');
  types.setTypeParser(20, Number); // BIGINT (COUNT(*), expires_at) as numbers
  const pool = new Pool({ connectionString: config.databaseUrl, max: config.onVercel ? 3 : 10, idleTimeoutMillis: 10000 });
  pool.on('error', (err) => console.error('[db] idle client error:', err.message));

  // "?" → "$1, $2 …", skipping question marks inside quoted SQL strings.
  const converted = new Map();
  const toPg = (sql) => {
    if (!converted.has(sql)) {
      let n = 0;
      let quoted = false;
      let out = '';
      for (const ch of sql) {
        if (ch === "'") quoted = !quoted;
        out += ch === '?' && !quoted ? `$${++n}` : ch;
      }
      converted.set(sql, out);
    }
    return converted.get(sql);
  };
  const api = (client) => ({
    all: async (sql, params = []) => (await client.query(toPg(sql), params)).rows,
    get: async (sql, params = []) => (await client.query(toPg(sql), params)).rows[0],
    run: async (sql, params = []) => { await client.query(toPg(sql), params); }
  });

  driver = {
    ...api(pool),
    async tx(fn) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const result = await fn(api(client));
        await client.query('COMMIT');
        return result;
      } catch (err) {
        await client.query('ROLLBACK').catch(() => {});
        throw err;
      } finally {
        client.release();
      }
    },
    async exec(sql) { await pool.query(sql); },
    close: () => pool.end()
  };
} else if (config.onVercel) {
  // Vercel's disk is read-only and temporary, so SQLite can't be used there.
  const missing = async () => {
    const err = new Error('No database is connected. Add a Postgres (Neon) database to this Vercel project.');
    err.code = 'DB_NOT_CONFIGURED';
    throw err;
  };
  driver = { all: missing, get: missing, run: missing, tx: missing, exec: missing, close: async () => {} };
} else {
  const { DatabaseSync } = require('node:sqlite');
  fs.mkdirSync(config.dataDir, { recursive: true });
  const sqlite = new DatabaseSync(config.dbFile);
  sqlite.exec('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON; PRAGMA busy_timeout = 5000;');
  const api = {
    all: async (sql, params = []) => sqlite.prepare(sql).all(...params),
    get: async (sql, params = []) => sqlite.prepare(sql).get(...params),
    run: async (sql, params = []) => { sqlite.prepare(sql).run(...params); }
  };
  driver = {
    ...api,
    async tx(fn) {
      sqlite.exec('BEGIN');
      try {
        const result = await fn(api);
        sqlite.exec('COMMIT');
        return result;
      } catch (err) {
        sqlite.exec('ROLLBACK');
        throw err;
      }
    },
    async exec(sql) { sqlite.exec(sql); },
    close: async () => sqlite.close(),
    sqlite // used by the backup script
  };
}

/* ---------------------------------------------------------------- Schema (created once per process) */

let readyPromise = null;
function ready() {
  if (!readyPromise) {
    readyPromise = (async () => {
      for (const statement of schema()) await driver.exec(statement);
    })().catch((err) => {
      readyPromise = null; // retry on the next request
      throw err;
    });
  }
  return readyPromise;
}

module.exports = { ...driver, ready, nowSql, isPg };
